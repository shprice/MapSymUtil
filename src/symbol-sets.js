/**
 * Return the human-readable label for an entity code within a given symbol set, or null.
 * @param {string} symbolSet  2-digit symbol set string, e.g. '11', '20', '60'.
 * @param {string} entityCode  6-character entity code (positions 10–15 of a 20-char SIDC).
 * @returns {string|null}
 */
export function ssLabel(symbolSet, entityCode) {
  const table = SS_ENTITIES[String(symbolSet)];
  return table?.[String(entityCode)] ?? null;
}

/**
 * Return true if the given 20-char 2525D SIDC belongs to one of the extended symbol sets
 * covered by this module (ss=11, 20, 27, 36, 40, 50–54, 60).
 * @param {string} sidc
 * @returns {boolean}
 */
export function isExtendedSidc(sidc) {
  return typeof sidc === 'string' && sidc.length === 20 && EXTENDED_SS_IDS.has(sidc.slice(4, 6));
}

/**
 * Parse a 20-char 2525D SIDC from an extended symbol set and return metadata, or null.
 *
 * @param {string} sidc
 * @returns {{ symbolSet:string, entityCode:string, label:string|null, standardIdentity:string }|null}
 */
export function parseExtendedSidc(sidc) {
  if (!isExtendedSidc(sidc)) return null;
  const symbolSet       = sidc.slice(4, 6);
  const entityCode      = sidc.slice(10, 16);
  const standardIdentity = sidc.slice(2, 4);
  return {
    symbolSet,
    entityCode,
    label:            ssLabel(symbolSet, entityCode),
    standardIdentity,
  };
}

/**
 * Build a 20-char 2525D SIDC for an entity code in an extended symbol set.
 *
 * @param {string} symbolSet   2-digit symbol set string, e.g. '20'.
 * @param {string} entityCode  6-character entity code.
 * @param {string} [si='01']   Standard identity 2-char string (e.g. '03' for Friend).
 * @returns {string}
 */
export function ssToSidc(symbolSet, entityCode, si = '01') {
  return `10${si}${String(symbolSet).padStart(2, '0')}0000${entityCode}0000`;
}

/**
 * Return all entities for a given symbol set as an array, optionally filtered by a 2-digit category prefix.
 *
 * @param {string} symbolSet       2-digit symbol set string.
 * @param {string} [categoryPrefix]  Leading 2 digits of entity code, e.g. '11'.
 * @returns {{ entityCode:string, label:string }[]}
 */
export function ssEntries(symbolSet, categoryPrefix) {
  const table = SS_ENTITIES[String(symbolSet)];
  if (!table) return [];
  return Object.entries(table)
    .filter(([code]) => !categoryPrefix || code.startsWith(categoryPrefix))
    .map(([entityCode, label]) => ({ entityCode, label }));
}
